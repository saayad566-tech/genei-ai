"""Film Blueprint.

The first artifact in the production flow the specification defines:

    USER IDEA -> FILM BLUEPRINT -> CHARACTER CREATION -> WORLD CREATION
              -> SHOT PLAN -> IMAGE GENERATION -> VIDEO GENERATION -> ...

The blueprint is the *plan*: what the film is about and how it is structured, before
any scene or shot exists. It is deliberately separate from the Project Brain (which
holds what is known and how well it is known) and from the Production Constitution
(which holds the rules production must obey).

Nothing here is generated by a model. It is the structure a model's output is fitted
into, and it validates itself: a blueprint missing a required part is reported invalid
rather than being used.
"""
from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class Beat:
    """One story beat: a change that moves the film forward."""

    id: str
    summary: str
    purpose: str
    act: int = 1
    sequence_id: Optional[str] = None


@dataclass
class SequencePlan:
    """A run of scenes that serves one objective."""

    id: str
    title: str
    act: int
    objective: str
    beats: List[Beat] = field(default_factory=list)
    estimated_scenes: int = 1


@dataclass
class FilmBlueprint:
    project_id: str
    title: str
    logline: str
    theme: str
    tone: str
    visual_style: str
    target_duration_seconds: float
    act_structure: List[str] = field(default_factory=list)
    sequences: List[SequencePlan] = field(default_factory=list)
    character_ids: List[str] = field(default_factory=list)
    world_ids: List[str] = field(default_factory=list)
    # Provenance: which brief this was derived from, and when.
    derived_from_brief: str = ""
    version: int = 1
    created_at: float = field(default_factory=time.time)
    revision_of: Optional[int] = None


# A blueprint that cannot answer these is not a plan, it is a placeholder.
REQUIRED_TEXT_FIELDS = ("title", "logline", "theme", "tone", "visual_style")


def create_film_blueprint(
    project_id: str,
    brief: str,
    *,
    title: str,
    logline: str = "",
    theme: str = "",
    tone: str = "cinematic",
    visual_style: str = "naturalistic",
    target_duration_seconds: float = 300.0,
    act_structure: Optional[List[str]] = None,
    sequences: Optional[List[SequencePlan]] = None,
) -> FilmBlueprint:
    """Build a blueprint from the user's idea.

    Defaults here are *structural*, not creative: a three-act skeleton and the brief's
    own title. Anything the caller does not supply stays empty and is reported by
    ``validate_film_blueprint`` rather than being invented.
    """
    return FilmBlueprint(
        project_id=project_id,
        title=title or "",
        logline=logline,
        theme=theme,
        tone=tone,
        visual_style=visual_style,
        target_duration_seconds=float(target_duration_seconds),
        act_structure=act_structure if act_structure is not None else ["Act I — Setup", "Act II — Confrontation", "Act III — Resolution"],
        sequences=sequences if sequences is not None else [],
        derived_from_brief=brief,
    )


def validate_film_blueprint(blueprint: FilmBlueprint) -> List[str]:
    """Return the reasons this blueprint is not usable. Empty means it is valid."""
    problems: List[str] = []

    for name in REQUIRED_TEXT_FIELDS:
        if not str(getattr(blueprint, name, "") or "").strip():
            problems.append(f"{name} is empty — the blueprint does not say what the film is")

    if not blueprint.derived_from_brief.strip():
        problems.append("derived_from_brief is empty — the blueprint cannot be traced to the user's idea")

    if blueprint.target_duration_seconds <= 0:
        problems.append("target_duration_seconds must be greater than zero")

    if not blueprint.act_structure:
        problems.append("act_structure is empty — there is no shape to the film")

    if not blueprint.sequences:
        problems.append("sequences is empty — no scene can be placed in the structure")

    # A sequence must belong to a declared act and carry an objective, or it is a label.
    acts = set(blueprint.act_structure)
    for sequence in blueprint.sequences:
        if sequence.act < 1 or sequence.act > len(blueprint.act_structure):
            problems.append(f"sequence {sequence.id} is in act {sequence.act}, which is outside the declared act structure")
        if not sequence.objective.strip():
            problems.append(f"sequence {sequence.id} has no objective")
        if sequence.estimated_scenes < 1:
            problems.append(f"sequence {sequence.id} estimates fewer than one scene")
        for beat in sequence.beats:
            if not beat.summary.strip():
                problems.append(f"beat {beat.id} in sequence {sequence.id} has no summary")
            if not beat.purpose.strip():
                problems.append(f"beat {beat.id} in sequence {sequence.id} has no purpose")

    # Coverage: every act should be served by at least one sequence, otherwise the film
    # silently has a hole in it.
    covered = {sequence.act for sequence in blueprint.sequences}
    if blueprint.sequences:
        for index in range(1, len(blueprint.act_structure) + 1):
            if index not in covered:
                problems.append(f"act {index} ({blueprint.act_structure[index - 1]}) has no sequence")

    _ = acts  # kept for readability of the check above
    return problems


def revise_film_blueprint(previous: FilmBlueprint, **changes) -> FilmBlueprint:
    """Produce a new revision.

    Revisions are new objects with ``version`` incremented and ``revision_of`` set, so
    the previous plan is never overwritten.
    """
    allowed = {
        "title", "logline", "theme", "tone", "visual_style", "target_duration_seconds",
        "act_structure", "sequences", "character_ids", "world_ids",
    }
    unknown = set(changes) - allowed
    if unknown:
        raise ValueError(f"cannot revise unknown blueprint field(s): {', '.join(sorted(unknown))}")

    data = {
        "project_id": previous.project_id,
        "title": previous.title,
        "logline": previous.logline,
        "theme": previous.theme,
        "tone": previous.tone,
        "visual_style": previous.visual_style,
        "target_duration_seconds": previous.target_duration_seconds,
        "act_structure": list(previous.act_structure),
        "sequences": list(previous.sequences),
        "character_ids": list(previous.character_ids),
        "world_ids": list(previous.world_ids),
        "derived_from_brief": previous.derived_from_brief,
    }
    data.update(changes)
    return FilmBlueprint(**data, version=previous.version + 1, revision_of=previous.version)


def blueprint_to_sequence_plan(blueprint: FilmBlueprint) -> List[dict]:
    """A flat, ordered view for the shot planner: one entry per sequence."""
    ordered = sorted(blueprint.sequences, key=lambda sequence: (sequence.act, sequence.id))
    return [
        {
            "sequence_id": sequence.id,
            "act": sequence.act,
            "title": sequence.title,
            "objective": sequence.objective,
            "estimated_scenes": sequence.estimated_scenes,
            "beat_ids": [beat.id for beat in sequence.beats],
        }
        for sequence in ordered
    ]
